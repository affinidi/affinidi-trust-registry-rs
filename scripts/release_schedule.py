#!/usr/bin/env python3
"""Generate the release schedule table in RELEASES.md from the git tags.

The table between the `release-schedule:begin` / `release-schedule:end`
markers in RELEASES.md is generated, never edited by hand. Its only input is
the repository's `v<major>.<minor>.<patch>[-rc.<n>]` tags, which the release
tooling creates (release-tag.yml): a tag's date is its creator date (the
tagged commit's committer date for a lightweight tag, the tagger date for an
annotated one), in UTC, the same day the changelog heading carries.

For each release line `major.minor` with at least one tag:

- First RC: the earliest `v<x.y>.0-rc.N` tag; a line cut without an rc tag
  (0.27, cut by the local script) shows its GA date.
- GA: the `v<x.y>.0` tag, or `—` while the line is still in release candidates.
- Latest: the line's highest version tag.
- Status: the newest GA line is `supported (N)`, the GA line below it
  `supported (N-1)` (RELEASES.md, Support). Every older GA line is
  `end of life (<date>)`, the date being the GA of the line two above it,
  which is what ended its support. A line not yet GA is `release candidate`.

Usage (Python >= 3.11, from anywhere in a checkout with the tags fetched):

    python3 scripts/release_schedule.py           # check: exit 1 if RELEASES.md differs
    python3 scripts/release_schedule.py --write   # rewrite the table in place

`release-schedule.yml` runs `--write` after every release tag and opens the
PR; the `release schedule` job in checks.yaml runs the check.
"""

from __future__ import annotations

import argparse
import dataclasses
import datetime
import difflib
import pathlib
import re
import subprocess
import sys

if sys.version_info < (3, 11):  # noqa: UP036 (run with whatever python3 is on PATH)
    raise SystemExit("the release scripts need Python >= 3.11")

ROOT = pathlib.Path(__file__).resolve().parent.parent
RELEASES_MD = ROOT / "RELEASES.md"

BEGIN = (
    "<!-- release-schedule:begin — generated by scripts/release_schedule.py "
    "from the v* tags; do not edit by hand -->"
)
END = "<!-- release-schedule:end -->"

TAG = re.compile(r"^v(\d+)\.(\d+)\.(\d+)(?:-rc\.(\d+))?$")

HEADER = (
    "| Release | Branch | First RC | GA | Latest | Status |\n"
    "|---|---|---|---|---|---|\n"
    "| ≤ 0.26 | — | — | — | `0.26.0` | published from `main` "
    "(`trust-registry-v…` tags) |\n"
)


@dataclasses.dataclass(frozen=True)
class Version:
    major: int
    minor: int
    patch: int
    # None for a GA or patch version; sorts after every rc of the same patch.
    rc: int | None

    @property
    def line(self) -> tuple[int, int]:
        return (self.major, self.minor)

    def sort_key(self) -> tuple[int, int, int, int, int]:
        rc_rank = (1, 0) if self.rc is None else (0, self.rc)
        return (self.major, self.minor, self.patch, *rc_rank)

    def __str__(self) -> str:
        base = f"{self.major}.{self.minor}.{self.patch}"
        return base if self.rc is None else f"{base}-rc.{self.rc}"


def parse_tag(name: str) -> Version | None:
    m = TAG.match(name)
    if not m:
        return None
    major, minor, patch, rc = m.groups()
    return Version(int(major), int(minor), int(patch), None if rc is None else int(rc))


def git_tags(cwd: pathlib.Path = ROOT) -> dict[Version, datetime.date]:
    """Every release tag with its UTC date."""
    out = subprocess.run(
        [
            "git",
            "for-each-ref",
            "--format=%(refname:strip=2) %(creatordate:unix)",
            "refs/tags/v*",
        ],
        capture_output=True,
        text=True,
        cwd=cwd,
        check=False,
    )
    if out.returncode:
        raise SystemExit(f"git for-each-ref failed:\n{out.stderr.strip()}")
    tags: dict[Version, datetime.date] = {}
    for row in out.stdout.splitlines():
        name, _, stamp = row.partition(" ")
        version = parse_tag(name)
        if version is None or not stamp:
            continue
        tags[version] = datetime.datetime.fromtimestamp(int(stamp), datetime.UTC).date()
    return tags


def render(tags: dict[Version, datetime.date]) -> str:
    """The table (header rows included) for these tags."""
    lines: dict[tuple[int, int], list[Version]] = {}
    for version in tags:
        lines.setdefault(version.line, []).append(version)

    def ga(line: tuple[int, int]) -> Version:
        return Version(*line, 0, None)

    ga_lines = sorted(line for line in lines if ga(line) in tags)
    status: dict[tuple[int, int], str] = {}
    for i, line in enumerate(ga_lines):
        above = len(ga_lines) - 1 - i
        if above == 0:
            status[line] = "supported (N)"
        elif above == 1:
            status[line] = "supported (N-1)"
        else:
            ended_by = ga(ga_lines[i + 2])
            status[line] = f"end of life ({tags[ended_by].isoformat()})"

    rows = [HEADER]
    for line in sorted(lines):
        versions = sorted(lines[line], key=Version.sort_key)
        name = f"{line[0]}.{line[1]}"
        rcs = [v for v in versions if v.patch == 0 and v.rc is not None]
        ga_date = tags.get(ga(line))
        first_rc = min(tags[v] for v in rcs) if rcs else ga_date
        rows.append(
            f"| {name} | `release/{name}` "
            f"| {first_rc.isoformat() if first_rc else '—'} "
            f"| {ga_date.isoformat() if ga_date else '—'} "
            f"| `{versions[-1]}` "
            f"| {status.get(line, 'release candidate')} |\n"
        )
    return "".join(rows)


def splice(document: str, table: str) -> str:
    """`document` with the text between the markers replaced by `table`."""
    try:
        head, rest = document.split(BEGIN + "\n", 1)
        _, tail = rest.split(END, 1)
    except ValueError:
        raise SystemExit(
            f"RELEASES.md must hold exactly the lines\n  {BEGIN}\n  {END}\n"
            "around the schedule table"
        ) from None
    if BEGIN in tail or END in tail:
        raise SystemExit("RELEASES.md holds the schedule markers more than once")
    return f"{head}{BEGIN}\n{table}{END}{tail}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--write", action="store_true", help="rewrite RELEASES.md instead of checking it"
    )
    parser.add_argument("--file", type=pathlib.Path, default=RELEASES_MD)
    args = parser.parse_args(argv)

    tags = git_tags(args.file.resolve().parent)
    if not tags:
        # A shallow or tagless checkout would otherwise yield an empty table.
        raise SystemExit("no v<major>.<minor>.<patch> tags here: run `git fetch --tags` first")

    current = args.file.read_text(encoding="utf-8")
    wanted = splice(current, render(tags))
    if current == wanted:
        print(f"{args.file.name}: the release schedule matches the tags")
        return 0
    if args.write:
        args.file.write_text(wanted, encoding="utf-8")
        print(f"{args.file.name}: release schedule updated")
        return 0
    sys.stdout.writelines(
        difflib.unified_diff(
            current.splitlines(keepends=True),
            wanted.splitlines(keepends=True),
            f"{args.file.name} (committed)",
            f"{args.file.name} (from the tags)",
        )
    )
    print(
        f"::error file={args.file.name}::the release schedule does not match the tags. "
        "Merge the open `docs(releases): update the release schedule` PR, or run "
        "`python3 scripts/release_schedule.py --write` and commit the result."
    )
    return 1


if __name__ == "__main__":
    sys.exit(main())
